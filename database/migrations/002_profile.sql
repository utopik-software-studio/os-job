CREATE TABLE IF NOT EXISTS experiences (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, profile_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(190) NOT NULL, organization VARCHAR(190) NOT NULL DEFAULT '',
 location VARCHAR(190) NOT NULL DEFAULT '', start_date VARCHAR(7) NOT NULL DEFAULT '',
 end_date VARCHAR(7) NOT NULL DEFAULT '', description TEXT NULL,
 FOREIGN KEY(profile_id) REFERENCES profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS profile_education (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, profile_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(190) NOT NULL, organization VARCHAR(190) NOT NULL DEFAULT '',
 start_date VARCHAR(7) NOT NULL DEFAULT '', end_date VARCHAR(7) NOT NULL DEFAULT '', description TEXT NULL,
 FOREIGN KEY(profile_id) REFERENCES profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS profile_skills (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, profile_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(150) NOT NULL, level VARCHAR(80) NOT NULL DEFAULT '', description TEXT NULL,
 FOREIGN KEY(profile_id) REFERENCES profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS profile_languages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, profile_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(100) NOT NULL, level VARCHAR(80) NOT NULL DEFAULT '', description TEXT NULL,
 FOREIGN KEY(profile_id) REFERENCES profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS career_targets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, profile_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(190) NOT NULL, level VARCHAR(80) NOT NULL DEFAULT '', description TEXT NULL,
 FOREIGN KEY(profile_id) REFERENCES profiles(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
