CREATE TABLE IF NOT EXISTS profiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 first_name VARCHAR(100) NOT NULL DEFAULT '', last_name VARCHAR(100) NOT NULL DEFAULT '',
 headline VARCHAR(200) NOT NULL DEFAULT '', email VARCHAR(190) NOT NULL DEFAULT '',
 phone VARCHAR(70) NOT NULL DEFAULT '', city VARCHAR(160) NOT NULL DEFAULT '',
 country VARCHAR(120) NOT NULL DEFAULT '', linkedin_url VARCHAR(500) NOT NULL DEFAULT '',
 website_url VARCHAR(500) NOT NULL DEFAULT '', summary TEXT NULL,
 salary_min INT UNSIGNED NOT NULL DEFAULT 45000,
 preferred_locations TEXT NULL, mobility VARCHAR(180) NOT NULL DEFAULT '',
 work_mode VARCHAR(80) NOT NULL DEFAULT '', availability VARCHAR(180) NOT NULL DEFAULT '',
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
